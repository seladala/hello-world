#!/usr/bin/env python3
"""Generates main.py: exactly 67,000 lines of enterprise-grade compliance.

Every compliance layer applies a mathematically reversible transformation to
the 64-bit fingerprint of the greeting and immediately reverses it, then
checks that nothing changed. Thousands of them. In sequence. Deterministically.

Usage: python tools/generate_main.py [--lines 67000] [--output main.py]
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

TARGET_LINES = 67_000
SEED = 67
MASK64 = (1 << 64) - 1

HEADER = '''\
#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
main.py - Ultimate Hello World, Enterprise Edition v6.7.0

THIS FILE IS GENERATED by tools/generate_main.py. DO NOT EDIT BY HAND.
It is exactly {target_lines} lines long, as required by the specification.

Pipeline overview:
    1. The Kernel resolves the component dependency graph and boots every service.
    2. The warm-up orchestrator verifies Collatz, counts primes, inverts
       the identity matrix and bogosorts a list. Results are discarded.
    3. Three independent algorithms compute 1000 digits of pi and reach
       Byzantine consensus.
    4. The UHX-16 CPU emulator runs its Power-On Self Test, then executes
       HELLO.ASM, which decrypts the greeting using pi-derived keys.
    5. Five officers of the Glyph Approval Committee vote on every
       character; approvals are mined into a proof-of-work blockchain.
    6. Letter case is negotiated over four rounds.
    7. The greeting's 64-bit fingerprint passes through {stage_count} compliance
       layers defined below, each of which provably changes nothing.
    8. The Terminal Rendering Engine converts glyph events into photons.

Run:  python main.py        -> hello world
      python main.py -v     -> hello world, plus everything nobody asked for
"""

from __future__ import annotations

import argparse
import hashlib
import logging
import sys

from ultimate_hello import __version__
from ultimate_hello.bootstrap import Kernel
from ultimate_hello.cpu import disassemble

log = logging.getLogger("main")

_MASK64 = 0xFFFFFFFFFFFFFFFF


class ComplianceViolation(Exception):
    """Raised when a compliance layer detects that mathematics has stopped working."""

    def __init__(self, layer: int, procedure: str) -> None:
        super().__init__(f"compliance layer {{layer:05d}} ({{procedure}}) altered the fingerprint")
        self.layer = layer
        self.procedure = procedure


def _fingerprint(message: str) -> int:
    """Derive the 64-bit Greeting Integrity Fingerprint (GIF)."""
    return int.from_bytes(hashlib.sha256(message.encode("utf-8")).digest()[:8], "big")


# =============================================================================
#  SECTION 1: COMPLIANCE LAYERS
#  Each layer is reviewed, signed and individually unit-tested by nobody.
# =============================================================================
'''

FOOTER = '''\

# =============================================================================
#  SECTION 4: ENTRY POINT
# =============================================================================


def run_compliance_pipeline(fingerprint: int) -> int:
    for layer in COMPLIANCE_PIPELINE:
        fingerprint = layer(fingerprint)
    return fingerprint


def _parse_args(argv):
    parser = argparse.ArgumentParser(description="Prints hello world. Eventually.")
    parser.add_argument("-v", "--verbose", action="count", default=0,
                        help="log the bureaucracy to stderr (-vv for debug)")
    parser.add_argument("--disassemble", action="store_true",
                        help="dump the HELLO.ASM machine code listing to stderr")
    parser.add_argument("--version", action="version", version=f"ultimate-hello {{__version__}}")
    return parser.parse_args(argv)


def main(argv=None) -> int:
    args = _parse_args(argv)
    level = logging.WARNING if not args.verbose else logging.INFO if args.verbose == 1 else logging.DEBUG
    logging.basicConfig(level=level, stream=sys.stderr, format="[%(levelname)-5s] %(name)s: %(message)s")

    kernel = Kernel.boot()
    if args.disassemble:
        firmware = kernel.container.get("firmware_loader").load("hello.asm")
        sys.stderr.write("\\n".join(disassemble(firmware.image)) + "\\n")

    message = kernel.produce_greeting()
    fingerprint = _fingerprint(message)
    if run_compliance_pipeline(fingerprint) != fingerprint:
        raise ComplianceViolation(0, "pipeline aggregate")
    log.info("all %d compliance layers passed; %d audit records on file",
             len(COMPLIANCE_PIPELINE), len(REGULATORY_AUDIT_TRAIL))

    kernel.render(message)
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''


def _procedures(rng: random.Random):
    """Yield (name, body_lines, rationale) for the next compliance procedure."""
    while True:
        kind = rng.randrange(6)
        if kind == 0:
            a = rng.getrandbits(64) | 1
            inv = pow(a, -1, 1 << 64)
            yield ("Multiplicative Inverse Reconciliation",
                   [f"fingerprint = (fingerprint * 0x{a:016X}) & _MASK64",
                    f"fingerprint = (fingerprint * 0x{inv:016X}) & _MASK64"],
                   "Multiplies by an odd constant and then by its inverse modulo 2**64.")
        elif kind == 1:
            k = rng.randrange(1, 64)
            yield ("Bitwise Rotation Round-Trip",
                   [f"fingerprint = ((fingerprint << {k}) | (fingerprint >> {64 - k})) & _MASK64",
                    f"fingerprint = ((fingerprint >> {k}) | (fingerprint << {64 - k})) & _MASK64"],
                   f"Rotates left by {k} bits, then right by {k} bits.")
        elif kind == 2:
            c = rng.getrandbits(64)
            yield ("Double XOR Notarization",
                   [f"fingerprint ^= 0x{c:016X}",
                    f"fingerprint ^= 0x{c:016X}"],
                   "Applies a one-time pad twice, which is exactly as secure as it sounds.")
        elif kind == 3:
            c = rng.getrandbits(64)
            yield ("Additive Escrow",
                   [f"fingerprint = (fingerprint + 0x{c:016X}) & _MASK64",
                    f"fingerprint = (fingerprint - 0x{c:016X}) & _MASK64"],
                   "Deposits a constant into escrow and withdraws it in full.")
        elif kind == 4:
            yield ("Byte Order Diplomacy",
                   ['fingerprint = int.from_bytes(fingerprint.to_bytes(8, "big"), "little")',
                    'fingerprint = int.from_bytes(fingerprint.to_bytes(8, "big"), "little")'],
                   "Converts between big- and little-endian camps and back again.")
        else:
            yield ("Two's Complement Pilgrimage",
                   ["fingerprint = -fingerprint & _MASK64",
                    "fingerprint = -fingerprint & _MASK64"],
                   "Walks to the negative half of the ring and returns enlightened.")


def _stage(index: int, total: int, name: str, body: list[str], rationale: str) -> list[str]:
    return [
        "",
        "",
        f"def _compliance_layer_{index:05d}(fingerprint: int) -> int:",
        f'    """Compliance layer {index:05d}/{total:05d}: {name}.',
        "",
        f"    {rationale}",
        f"    Regulatory basis: ISO/IEC 9001-HW, clause {index // 100}.{index % 100:02d}.",
        '    """',
        "    witness = fingerprint",
        *(f"    {line}" for line in body),
        "    if fingerprint != witness:",
        f'        raise ComplianceViolation({index}, "{name}")',
        "    return fingerprint",
    ]


STAGE_LINES = 14      # lines emitted by _stage()
PER_STAGE = STAGE_LINES + 2  # + one pipeline entry + one audit record


def generate(target_lines: int) -> str:
    header = HEADER.format(target_lines=target_lines, stage_count="{stage_count}").splitlines()
    footer = FOOTER.format().splitlines()
    pipeline_frame = ["", "", "# " + "=" * 77,
                      "#  SECTION 2: THE COMPLIANCE PIPELINE (order is legally binding)",
                      "# " + "=" * 77, "", "COMPLIANCE_PIPELINE = (", ")"]
    audit_frame = ["", "", "# " + "=" * 77,
                   "#  SECTION 3: REGULATORY AUDIT TRAIL",
                   "# " + "=" * 77, "", "REGULATORY_AUDIT_TRAIL = (", ")"]
    fixed = len(header) + len(footer) + len(pipeline_frame) + len(audit_frame)
    stage_count, padding = divmod(target_lines - fixed, PER_STAGE)
    if stage_count <= 0:
        raise SystemExit("target too small for even a single layer of compliance")

    rng = random.Random(SEED)
    procedures = _procedures(rng)
    stages, pipeline, audit = [], [], []
    for index in range(1, stage_count + 1):
        name, body, rationale = next(procedures)
        stages += _stage(index, stage_count, name, body, rationale)
        pipeline.append(f"    _compliance_layer_{index:05d},")
        audit.append(f'    "AUDIT-{index:05d} | {name:<38} | VERIFIED | signed: Chief Hello Officer",')
    for extra in range(1, padding + 1):
        audit.append(f'    "AUDIT-R{extra:04d} | reserved for future compliance       | PENDING  | signed: nobody",')

    header = [line.replace("{stage_count}", str(stage_count)) for line in header]
    lines = (header + stages
             + pipeline_frame[:-1] + pipeline + pipeline_frame[-1:]
             + audit_frame[:-1] + audit + audit_frame[-1:]
             + footer)
    assert len(lines) == target_lines, (len(lines), target_lines)
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lines", type=int, default=TARGET_LINES)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parent.parent / "main.py")
    args = parser.parse_args()
    args.output.write_text(generate(args.lines), encoding="utf-8")
    print(f"wrote {args.output} ({args.lines} lines)")


if __name__ == "__main__":
    main()
